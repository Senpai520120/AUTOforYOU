def _slugify_uk(text: str) -> str:
    transliteration = {
        'а': 'a', 'б': 'b', 'в': 'v', 'г': 'h', 'ґ': 'g', 'д': 'd', 'е': 'e',
        'є': 'ye', 'ж': 'zh', 'з': 'z', 'и': 'y', 'і': 'i', 'ї': 'yi', 'й': 'y',
        'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r',
        'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch',
        'ш': 'sh', 'щ': 'shch', 'ь': '', 'ю': 'yu', 'я': 'ya',
        "'": '', '\u2019': '', '\u02bc': '',
    }
    result = []
    for ch in text.lower():
        result.append(transliteration.get(ch, ch))
    slug = ''.join(result)
    return slugify(slug, allow_unicode=False)


class Command(BaseCommand):
    help = 'Засіває довідник областей і міст України (неповний — дозасіяти повним КАТОТТГ)'

    def add_arguments(self, parser):
        parser.add_argument('--clear', action='store_true', help='Видалити існуючі дані перед засівом')

    def handle(self, *args, **options):
        if options['clear']:
            City.objects.all().delete()
            Region.objects.all().delete()
            self.stdout.write('Очищено.')

        regions_created = 0
        cities_created = 0

        for region_name, cities in _REGIONS:
            slug = _slugify_uk(region_name)
            region, created = Region.objects.get_or_create(
                name=region_name,
                defaults={'slug': slug},
            )
            if created:
                regions_created += 1

            for city_name in cities:
                city_slug = _slugify_uk(city_name)
                _, c_created = City.objects.get_or_create(
                    region=region,
                    slug=city_slug,
                    defaults={'name': city_name},
                )
                if c_created:
                    cities_created += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'Готово: {regions_created} нових областей, {cities_created} нових міст. '
                f'Всього: {Region.objects.count()} областей, {City.objects.count()} міст.\n'
                f'# Неповний довідник: дозасіяти повним КАТОТТГ.'
            )
        )
